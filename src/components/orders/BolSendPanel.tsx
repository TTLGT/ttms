'use client';

import { useCallback, useEffect, useState } from 'react';
import { Send } from 'lucide-react';
import { getBolRequest, markBolRequestDone, sendBol } from '@/lib/bolRequestsClient';
import { useDateFormatters } from '@/lib/useDateFormatters';
import { BOL_STATUS_LABEL, type BolRecipient, type BolRequest } from '@/types/bolRequest';

/**
 * Inside the Bill of Lading card on an order: where the BOL request stands,
 * and — for admin and dispatch — the people on the load to send it to.
 *
 * Nothing is ticked to start with. Who gets a BOL differs by load, and a
 * pre-ticked box is a decision nobody made. Somebody with no address on file
 * is shown, greyed, so the reason they cannot be chosen is on the screen.
 *
 * `bolVersion` changes whenever the BOL is generated on the page, so the
 * panel re-reads and picks up a request TTMS has just opened.
 */
export default function BolSendPanel({ orderId, bolVersion }: { orderId: string; bolVersion: string }) {
  const { formatDateTime } = useDateFormatters();
  const [data, setData] = useState<{ request: BolRequest | null; isSender: boolean; recipients: BolRecipient[] } | null>(null);
  const [picked, setPicked] = useState<string[]>([]);
  const [busy, setBusy] = useState<'' | 'send' | 'done'>('');
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');

  const load = useCallback(() => {
    getBolRequest(orderId).then(setData).catch((e) => setError(e instanceof Error ? e.message : 'Could not load the BOL request'));
  }, [orderId]);
  useEffect(() => { load(); }, [load, bolVersion]);

  if (!data) return error ? <p className="text-xs text-red-600 mt-3">{error}</p> : null;
  const { request, isSender, recipients } = data;
  if (!request && !isSender) return null;

  async function send() {
    setBusy('send'); setError(''); setNotice('');
    try {
      await sendBol(orderId, picked);
      setNotice(`Sent to ${recipients.filter((r) => picked.includes(r.key)).map((r) => r.email).join(', ')}.`);
      setPicked([]);
      load();
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Could not send the BOL');
    } finally {
      setBusy('');
    }
  }

  async function done() {
    setBusy('done'); setError('');
    try {
      await markBolRequestDone(orderId);
      load();
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Could not mark it done');
    } finally {
      setBusy('');
    }
  }

  return (
    <div className="mt-4 border-t border-gray-100 pt-4 space-y-3">
      {request && (
        <div className="flex flex-wrap items-center gap-2 text-xs">
          <span className={`rounded-full border px-2 py-0.5 font-semibold ${
            request.status === 'done' ? 'bg-green-50 text-green-700 border-green-200'
            : request.status === 'sent' ? 'bg-blue-50 text-blue-700 border-blue-200'
            : 'bg-brand-50 text-brand-700 border-brand-200'
          }`}>{BOL_STATUS_LABEL[request.status]}</span>
          <span className="text-gray-500">
            {request.openedBecause ? `${request.openedBecause}, so TTMS generated the BOL` : 'Generated by TTMS'} · {formatDateTime(new Date(request.openedAt))}
          </span>
          {request.status === 'done' && request.doneByName && request.doneAt && (
            <span className="text-gray-500">· Done by {request.doneByName}, {formatDateTime(new Date(request.doneAt))}</span>
          )}
        </div>
      )}

      {request && request.sends.length > 0 && (
        <ul className="text-xs text-gray-600 space-y-1">
          {request.sends.map((s, i) => (
            <li key={i}>
              Sent by {s.byName} · {formatDateTime(new Date(s.at))} — {s.to.map((t) => `${t.label} (${t.email})`).join(', ')}
            </li>
          ))}
        </ul>
      )}

      {isSender && (
        <div>
          <p className="text-xs font-semibold text-gray-700 mb-1.5">Send the BOL to</p>
          {recipients.length === 0 ? (
            <p className="text-xs text-gray-400">Nobody on this load has a record to send it to yet.</p>
          ) : (
            <div className="flex flex-wrap gap-2">
              {recipients.map((r) => {
                const on = picked.includes(r.key);
                return (
                  <label key={r.key}
                    title={r.email ? r.email : 'No email address on file'}
                    className={`flex items-center gap-2 rounded-lg border px-3 py-1.5 text-xs ${
                      !r.email ? 'border-gray-200 text-gray-400 cursor-not-allowed'
                      : on ? 'border-brand-300 bg-brand-50 text-brand-800 cursor-pointer'
                      : 'border-gray-300 text-gray-700 hover:bg-gray-50 cursor-pointer'}`}>
                    <input type="checkbox" disabled={!r.email || busy !== ''} checked={on}
                      onChange={() => setPicked(on ? picked.filter((k) => k !== r.key) : [...picked, r.key])} />
                    <span>
                      <span className="font-semibold">{r.label}</span>
                      {r.name && <span> · {r.name}</span>}
                      <span className="block text-[11px] text-gray-500">{r.email || 'No email on file'}</span>
                    </span>
                  </label>
                );
              })}
            </div>
          )}
          <div className="flex flex-wrap items-center gap-2 mt-3">
            <button type="button" onClick={send} disabled={picked.length === 0 || busy !== ''}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 bg-brand-600 text-white text-xs font-semibold rounded-lg hover:bg-brand-700 disabled:opacity-50 transition">
              <Send className="w-3.5 h-3.5" />
              {busy === 'send' ? 'Sending…' : 'Send BOL'}
            </button>
            {request && request.status !== 'done' && (
              <button type="button" onClick={done} disabled={busy !== ''}
                className="px-3 py-1.5 border border-gray-300 text-gray-700 text-xs font-medium rounded-lg hover:bg-gray-50 disabled:opacity-50 transition">
                {busy === 'done' ? 'Saving…' : 'Mark done'}
              </button>
            )}
          </div>
        </div>
      )}

      {notice && <p className="text-xs text-green-700">{notice}</p>}
      {error && <p className="text-xs text-red-600">{error}</p>}
    </div>
  );
}
