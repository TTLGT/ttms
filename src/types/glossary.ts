export interface GlossaryTerm {
  /** Stored in `vocabulary/{uid}.words` — never rename one. */
  id: string;
  /** The form shown at the top of the card. */
  word: string;
  /** Spanish, as short as it can be while still being right. */
  es: string;
  /** Plain English, one sentence, words a learner already knows. */
  meaning: string;
  /** A sentence somebody here might actually say or read. */
  example: string;
  category: GlossaryCategory;
  /**
   * Other spellings that open the same card. Leave it out and the plural is
   * worked out (see pluralOf); give an empty list for a word that has none.
   *
   * A form written all in capitals — BOL, ETA, MC — matches only in capitals,
   * so "pod" in a sentence is not mistaken for a proof of delivery.
   */
  forms?: string[];
}

