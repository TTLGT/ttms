export const GLOSSARY_BY_ID: ReadonlyMap<string, GlossaryTerm> =
  new Map(GLOSSARY.map((t) => [t.id, t]));

export function isGlossaryId(value: unknown): value is string {
  return typeof value === 'string' && GLOSSARY_BY_ID.has(value);
}

/**
 * The regular English plural, which covers every noun on the list that does
 * not spell its own forms out. Irregular ones (party → parties is regular;
 * a few like "bills of lading" are not) are written into `forms` instead.
 */
function pluralOf(word: string): string {
  if (/[^aeiou]y$/i.test(word)) return word.slice(0, -1) + 'ies';
  if (/(s|x|z|ch|sh)$/i.test(word)) return word + 'es';
  return word + 's';
}

export function formsOf(term: GlossaryTerm): string[] {
  return [term.word, ...(term.forms ?? [pluralOf(term.word)])];
}

/** All capitals, like BOL or ETA: matched only exactly as written. */
export function isAcronym(form: string): boolean {
  return /^[A-Z]{2,}s?$/.test(form);
}
