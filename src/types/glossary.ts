/**
 * The Learn English word list.
 *
 * TTMS is not translated, on purpose — the company works in English with US
 * clients and carriers, and the point is to help people read it, not to route
 * around it. When somebody turns on Learn English (see LearnContext), every
 * word on this list gets a dotted underline wherever it appears on screen, and
 * hovering or tapping it opens a card with the Spanish, a plain-English
 * meaning and an example.
 *
 * **Written by hand, not machine-translated, and that is the feature.** A
 * translation service turns "consignee" and "lane" into nonsense, and those are
 * exactly the words somebody new to freight does not know. The Spanish leans
 * Guatemalan where the two differ ("piloto", "marchamo", "bodega") because that
 * is where the team is.
 *
 * Plain data, no Firestore and no DOM, so the words page, the underliner and
 * the API route that validates ids all read the same list. **An id is stored**
 * in each person's `vocabulary/{uid}` record, so renaming one orphans their
 * history for that word — add a new id rather than changing an old one.
 * Changing a word's text, Spanish or meaning is free.
 */

export type GlossaryCategory =
  | 'loads'
  | 'companies'
  | 'money'
  | 'paperwork'
  | 'trucks'
  | 'screen'
  | 'office';

